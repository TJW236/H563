/* PI 控制器（照抄 G431 7-31 定稿） */
typedef struct {
    float kp;               /* 比例增益 */
    float ki;               /* 积分增益 */
    float kd;               /* 微分增益（位置环用，本版未用） */
    float max;              /* 输出限幅 */
    float dt;               /* 采样周期（秒） */
    float integral1;        /* 积分累计值 */
    float integral_limit;   /* 积分硬限幅（= max / ki），防止积分饱和 */
    float error_threshold;  /* 条件积分阈值：|error|>此值时不积分反而衰减；0=全程积分 */
    float i_decay;          /* 大误差时积分衰减系数（典型 0.98，每周期衰减 2%） */
} PI_t;

void PI_Init(PI_t *p, float kp, float ki, float max, float dt);
/* enable_integrate=0 时只跑 P 项（I 项保留当前值不累加），用于速度环防 windup */
