/* +0.5 四舍五入误差减半（≤0.35°）。索引掩码天然处理超 2π 正角（k×1024 被模掉，
 * 与 fmodf 折回结果索引相同）——09-04 去 fmodf：旋转时 Park cos 越界(25%)+SVPWM
 * sector5/6 路径必踩，-O0 下每次 ~1.3µs，曾使 ISR 超周期丢拍（30kHz 实跑 24.3kHz）。
 * 负角：调用域全集 [0, 2.5π]（elec16 为 uint16 强转，ENC_DIR 在 int32 域消化，
 * 恒非负）；if 兜底仅防未来调用方，fast_cos(x)=fast_sin(x+π/2) 的 x≥0 → 加一次 2π 必回正 */
static inline float fast_sin(float angle) {
  if (angle < 0.0f) angle += TWO_PI;
  uint32_t idx = ((uint32_t)(angle / TWO_PI * SIN_TABLE_SIZE + 0.5f)) & (SIN_TABLE_SIZE - 1u);
  return sin_table[idx];
}

static inline float fast_cos(float angle) {
  return fast_sin(angle + PI_F * 0.5f);
}

